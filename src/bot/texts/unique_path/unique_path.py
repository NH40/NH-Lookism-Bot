GAUGE_LINE = "\n📊 <b>{name}:</b> {value}/{cap} (из {maximum})"


def gauge_line(code: str | None, value: float, level: int) -> str:
    """Строка шкалы для экрана пути. Потолок зависит от уровня пути."""
    from bot.config.path_gauge import GAUGE_MAX, PATH_GAUGES, gauge_cap

    if code not in PATH_GAUGES or code not in GAUGE_NAMES:
        return ""
    return GAUGE_LINE.format(name=GAUGE_NAMES[code], value=f"{value:.1f}", cap=f"{gauge_cap(level):g}", maximum=f"{GAUGE_MAX:g}")

